"""
Index of the declarations in the inherited Maths 5 Lean sources (floor/lean_M5/lean/), taken from the Lean source text only: for each module, its imports and each
theorem / lemma / def / structure / inductive signature (up to the first `:=` or `where`, or 700 characters).  Comments are not copied.  New file (2026-11-03).
Usage:  py -3 -I -X utf8 -u explore/lean_M5_index.py > floor/lean_M5/DECLARATION_INDEX.md
"""
import os, re, glob, hashlib
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.normpath(os.path.join(here, '..', 'floor', 'lean_M5', 'lean'))
def strip_comments(s):
    out = []; i = 0; depth = 0
    while i < len(s):
        if s.startswith('/-', i): depth += 1; i += 2; continue
        if depth and s.startswith('-/', i): depth -= 1; i += 2; continue
        if depth: i += 1; continue
        if s.startswith('--', i):
            while i < len(s) and s[i] != '\n': i += 1
            continue
        out.append(s[i]); i += 1
    return ''.join(out)
print('# Declaration index of the inherited Maths 5 Lean sources\n')
print('Generated by `explore/lean_M5_index.py` from `floor/lean_M5/lean/` (byte copies; hashes in `MANIFEST.sha256`). Signatures only, comments omitted. The proof of each declaration is its body in the source file; the compile result for every module is in `explore/lean_M5_check.out`.\n')
files = sorted(glob.glob(os.path.join(root, 'Container*', '*.lean')))
kw = re.compile(r'^(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+|noncomputable\s+)*(theorem|lemma|def|abbrev|structure|inductive|class|instance)\s+(\S+)', re.M)
nd = 0
for f in files:
    rel = os.path.relpath(f, root).replace(os.sep, '/'); raw = open(f, encoding='utf-8').read(); src = strip_comments(raw)
    imps = re.findall(r'^import\s+(\S+)', src, re.M)
    decls = []
    for m in kw.finditer(src):
        start = m.start(); seg = src[start:start+4000]
        cut = len(seg)
        for tok in (':=', ' where', '\n  |', '\nwith'):
            j = seg.find(tok)
            if j != -1: cut = min(cut, j)
        sig = re.sub(r'\s+', ' ', seg[:cut]).strip()
        if len(sig) > 700: sig = sig[:700] + ' …'
        decls.append((m.group(1), sig))
    nd += len(decls)
    print(f'## {rel}  ·  imports: {", ".join(imps) if imps else "none"}  ·  {len(decls)} declarations  ·  sha256 {hashlib.sha256(open(f, "rb").read()).hexdigest()[:16]}\n')
    for k, sig in decls:
        print(f'- `{sig}`')
    print()
print(f'Total declarations indexed: {nd}')
