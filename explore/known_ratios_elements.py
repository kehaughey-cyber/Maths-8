# The raw known-ratios map for other elements, side by side with carbon. Values only (no logs, no exponents, no re-expression in any base). New file; nothing fitted.
# For each element the most abundant isotope with a measured charge radius in the IAEA livechart ground-state table is used (radius = Angeli & Marinova compilation, binding energy per nucleon and masses from AME).
# Atomic quantities (ionization energies, shells) come from PeriodicTableJSON (Wikipedia-derived, not NIST-checked). Constants as in the carbon maps.
# Run: py -3 -I -X utf8 -u explore/known_ratios_elements.py > maps/known_ratios_elements.md   (also writes maps/known_ratios_elements.csv)
import csv, json, os
from math import pi, sqrt
HERE = os.path.dirname(os.path.abspath(__file__)); DATA = os.path.join(HERE, 'data'); MAPS = os.path.join(HERE, '..', 'maps')
al = 7.2973525693e-3; hbarc = 1.973269804e-7; Ry = 13.605693123; me = 0.51099895e6; mp = 938.27208816e6; mP = 1.220890e28; a0 = 5.29177210903e-11; u_eV = 931494102.42
lam_p = hbarc/mp*1e15; lam_e = hbarc/me*1e15            # fm
rows = list(csv.DictReader(open(os.path.join(DATA, 'iaea_livechart_ground_states.csv'), encoding='utf-8')))
EL = {e['symbol']: e for e in json.load(open(os.path.join(DATA, 'PeriodicTableJSON.json'), encoding='utf-8'))['elements']}
want = ['H', 'He', 'Li', 'Be', 'B', 'C', 'N', 'O', 'F', 'Ne', 'Na', 'Mg', 'Al', 'Si', 'S', 'Ca', 'Fe', 'Ni', 'Cu', 'Ag', 'Sn', 'Au', 'Pb', 'U']
Z_of = {e['symbol']: e['number'] for e in EL.values()}
def pick(sym):
    cand = [r for r in rows if r['symbol'] == sym and int(r['z']) == Z_of[sym] and r['radius'] not in ('', None) and r['binding'] not in ('', None)]
    if not cand: return None
    cand.sort(key=lambda r: -(float(r['abundance']) if r['abundance'] else 0.0))
    return cand[0]
data = []
for s in want:
    r = pick(s)
    if r is None: print('# missing', s); continue
    Z = int(r['z']); N = int(r['n']); A = Z + N; rch = float(r['radius']); BA = float(r['binding'])*1e3          # eV per nucleon
    B = BA*A; ie = [x/96.485332 for x in EL[s]['ionization_energies']]; sh = EL[s]['shells']; n = len(sh)
    ie1 = ie[0]; zeff = n*sqrt(ie1/Ry); Rval = n*a0/sqrt(ie1/Ry)
    d = dict(el=s, iso='%d%s' % (A, s), Z=Z, N=N, rch=rch, ab=float(r['abundance']) if r['abundance'] else 0.0)
    d['rch/lam_p'] = rch/lam_p; d['rch/A^(1/3) (fm)'] = rch/A**(1/3); d['lam_e/rch'] = lam_e/rch; d['B/A (eV)'] = BA; d['(B/A)/m_p c^2'] = BA/mp; d['(B/A)/Ry'] = BA/Ry
    d['B r_ch/hbar c'] = B*rch*1e-15/hbarc; d['Z alpha'] = Z*al; d['N/Z'] = N/Z
    d['IE1 (eV)'] = ie1; d['IE1/Ry'] = ie1/Ry; d['n (period)'] = n; d['Z_eff = n sqrt(IE1/Ry)'] = zeff; d['R_val/a0 = n^2/Z_eff'] = n*n/zeff; d['R_val/r_ch'] = Rval/(rch*1e-15)
    d['R_val/lam_e'] = Rval/(lam_e*1e-15)
    d['sum of all Z ionization energies (eV)'] = sum(ie) if len(ie) == Z else None; d['IEs listed / Z'] = '%d/%d' % (len(ie), Z)
    d['sum IEs / B (nuclear)'] = sum(ie)/B if (len(ie) == Z and B > 0) else None
    d['IE_Z/(Z^2 Ry)'] = ie[Z-1]/(Z*Z*Ry) if len(ie) >= Z else None
    d['m_nucleus/m_P'] = (float(r['atomic_mass'])*1e-6*u_eV - Z*me)/mP if r['atomic_mass'] else None
    data.append(d)
names = [k for k in data[0].keys() if k not in ('el', 'iso', 'Z', 'N', 'rch', 'ab')]
print('# Known ratios for other elements, raw values (2026-10-29)')
print()
print('Generated by `explore/known_ratios_elements.py`. Values only, no logarithms or exponents. One isotope per element: the most abundant with a measured charge radius in the IAEA livechart ground-state table (`explore/data/iaea_livechart_ground_states.csv`: radius = Angeli & Marinova compilation, binding energy per nucleon and atomic mass from AME). Atomic quantities from PeriodicTableJSON (Wikipedia-derived, not NIST-checked); n = number of shells, Z_eff = n sqrt(IE1/Ry), R_val = n a0/sqrt(IE1/Ry) are hydrogenic constructions, not measured radii. Constants as in the carbon maps. Carbon is the reference column.')
print()
print('## Nuclei and atoms side by side (rows are ratios, columns are elements)')
print()
hdr = ['ratio'] + ['%s (%s)' % (d['el'], d['iso']) for d in data]
print('| ' + ' | '.join(hdr) + ' |'); print('|' + '---|'*len(hdr))
def fmt(v):
    if v is None: return 'n/a'
    if isinstance(v, str): return v
    return '%.6g' % v
for k in ['Z', 'N', 'rch'] + names:
    lab = {'rch': 'r_ch (fm)'}.get(k, k)
    print('| %s | ' % lab + ' | '.join(fmt(d[k]) if k in d else '' for d in data) + ' |')
print()
print('## Spread of each ratio across the elements listed')
print()
print('| ratio | min | max | max / min | carbon |')
print('|---|---|---|---|---|')
carb = next(d for d in data if d['el'] == 'C')
for k in names:
    vs = [d[k] for d in data if isinstance(d.get(k), (int, float)) and d[k] > 0]
    if not vs: continue
    print('| %s | %s | %s | %s | %s |' % (k, fmt(min(vs)), fmt(max(vs)), fmt(max(vs)/min(vs)), fmt(carb.get(k))))
with open(os.path.join(MAPS, 'known_ratios_elements.csv'), 'w', newline='', encoding='utf-8') as f:
    w = csv.writer(f); w.writerow(['element', 'isotope', 'Z', 'N', 'r_ch (fm)'] + names)
    for d in data: w.writerow([d['el'], d['iso'], d['Z'], d['N'], d['rch']] + [d.get(k) for k in names])
